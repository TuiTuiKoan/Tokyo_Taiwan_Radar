// Generates assets/qr.js (QR module matrix) from npm's bundled qrcode-terminal encoder.
const path = require('path');
const fs = require('fs');
const base = path.join(path.dirname(process.execPath), '../lib/node_modules/npm/node_modules/qrcode-terminal/vendor/QRCode');
const QRCode = require(base);
const QRErrorCorrectLevel = require(base + '/QRErrorCorrectLevel');
const url = process.argv[2] || 'https://www.amazon.co.jp/dp/B07ZPLQT14';
const qr = new QRCode(-1, QRErrorCorrectLevel.M);
qr.addData(url);
qr.make();
const n = qr.getModuleCount();
const rows = [];
for (let r = 0; r < n; r++) {
  let s = '';
  for (let c = 0; c < n; c++) s += qr.isDark(r, c) ? '1' : '0';
  rows.push(s);
}
fs.writeFileSync(path.join(__dirname, 'assets/qr.js'),
  `// Auto-generated by make_qr.js — ${url}\nwindow.QR_URL=${JSON.stringify(url)};\nwindow.QR_ROWS=${JSON.stringify(rows)};\n`);
console.log('modules', n);
